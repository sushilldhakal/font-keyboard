// Generates transliteration/schemes.ts from the shared JSON schemes (the single source of truth
// that the Android and iOS keyboards also bundle). Run automatically before build and test.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "..", "transliteration", "schemes");
const schemes = readdirSync(dir).filter((f) => f.endsWith(".json")).sort().map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")));
const camel = (id) => id.replace(/-(\w)/g, (_, c) => c.toUpperCase());
let ts = `// GENERATED by scripts/gen-schemes.mjs from transliteration/schemes/*.json. Do not edit.\n\n`;
ts += `export interface Scheme {\n  id: string;\n  name: string;\n  description: string;\n  finalVirama: boolean;\n  vowels: [key: string, letter: string, sign: string][];\n  consonants: [key: string, letter: string][];\n  marks: [key: string, sign: string][];\n  symbols: [key: string, symbol: string][];\n}\n\n`;
for (const s of schemes) {
  const { roman, ...rest } = s;
  ts += `export const ${camel(s.id)}: Scheme = ${JSON.stringify(rest)};\n\n`;
}
const ldir = join(here, "..", "transliteration", "layouts");
const layouts = readdirSync(ldir).filter((f) => f.endsWith(".json")).sort().map((f) => JSON.parse(readFileSync(join(ldir, f), "utf8")));
ts += `export interface Layout {\n  id: string;\n  name: string;\n  description: string;\n  rows: string[][];\n  shiftOf: Record<string, string>;\n  keys: Record<string, string>;\n}\n\n`;
ts += `export const layouts: Record<string, Layout> = ${JSON.stringify(Object.fromEntries(layouts.map((l) => [l.id, l])))};\n\n`;
const kdir = join(here, "..", "keyboards");
const keyboards = readdirSync(kdir).filter((f) => f.endsWith(".json")).sort().map((f) => JSON.parse(readFileSync(join(kdir, f), "utf8")));
ts += `/** A phone key: [tap, hold or Shift] ("" when the key has no second letter). */\nexport type PhoneKey = [tap: string, hold: string];\n\n`;
ts += `export interface PhoneLayout {\n  id: string;\n  name: string;\n  description: string;\n  rows: PhoneKey[][];\n  bottom: PhoneKey[];\n  numbers: PhoneKey[][];\n}\n\n`;
ts += `export const keyboards: Record<string, PhoneLayout> = ${JSON.stringify(Object.fromEntries(keyboards.map((k) => [k.id, k])))};\n\n`;
ts += `export const schemes: Record<string, Scheme> = { ${schemes.map((s) => `"${s.id}": ${camel(s.id)}`).join(", ")} };\n`;
writeFileSync(join(here, "..", "transliteration", "schemes.ts"), ts);
console.log(`schemes.ts: ${schemes.map((s) => s.id).join(", ")}`);
